    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT BOOKING_ID) AS DISTINCT_BOOKINGS
FROM GOLD.FACT;

SELECT
    BOOKING_ID,
    LISTING_ID,
    HOST_ID,
    COUNT(*) AS ROW_COUNT
FROM GOLD.FACT
GROUP BY BOOKING_ID, LISTING_ID, HOST_ID
HAVING COUNT(*) > 1
ORDER BY ROW_COUNT DESC
LIMIT 10;

SELECT
    LISTING_ID,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT BOOKING_ID) AS UNIQUE_BOOKINGS
FROM GOLD.FACT
GROUP BY LISTING_ID
ORDER BY ROW_COUNT DESC
LIMIT 10;

